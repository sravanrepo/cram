-- 1. CONTAINERS / SITES TABLE
CREATE TABLE ARM_CONTAINERS (
    CONTAINER_ID        NUMBER(12) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTAINER_CODE      VARCHAR2(64) NOT NULL UNIQUE,
    CONTAINER_NAME      VARCHAR2(255) NOT NULL,
    CONTAINER_TYPE      VARCHAR2(64) NOT NULL,       -- e.g., 'DC', 'POP', 'SHELF', 'RACK'
    STATUS              VARCHAR2(32) DEFAULT 'ACTIVE' NOT NULL, -- 'ACTIVE', 'PLANNED', 'DECOMMISSIONED'
    SITE_CODE           VARCHAR2(32),
    COUNTRY             VARCHAR2(64),
    REGION              VARCHAR2(64),
    MAX_CAPACITY_UNITS  NUMBER(10) DEFAULT 0,
    USED_CAPACITY_UNITS NUMBER(10) DEFAULT 0,
    TOTAL_SLOTS         NUMBER(6) DEFAULT 0,
    USED_SLOTS          NUMBER(6) DEFAULT 0,
    CREATED_DATE        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_DATE        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_ARM_CONT_TYPE ON ARM_CONTAINERS(CONTAINER_TYPE);
CREATE INDEX IDX_ARM_CONT_STATUS ON ARM_CONTAINERS(STATUS);
CREATE INDEX IDX_ARM_CONT_SITE ON ARM_CONTAINERS(SITE_CODE);

COMMENT ON TABLE ARM_CONTAINERS IS 'Stores physical and logical container structures such as racks, shelves, POPs, and data center locations.';
COMMENT ON COLUMN ARM_CONTAINERS.CONTAINER_CODE IS 'Unique human-readable container code/identifier.';
COMMENT ON COLUMN ARM_CONTAINERS.CONTAINER_TYPE IS 'Classification of container (e.g., Container Type, Slot Shelf Type).';


-- 2. ENTITIES / HARDWARE DEVICES TABLE
CREATE TABLE ARM_ENTITIES (
    ENTITY_ID           NUMBER(12) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENTITY_CODE         VARCHAR2(64) NOT NULL UNIQUE,
    ENTITY_NAME         VARCHAR2(255) NOT NULL,
    ENTITY_TYPE         VARCHAR2(64) NOT NULL,       -- e.g., 'Device Type', 'Router', 'Switch', 'Optical'
    SUBTYPE_NAME        VARCHAR2(128),
    MANUFACTURER        VARCHAR2(128),
    MODEL_NUMBER        VARCHAR2(128),
    CONTAINER_ID        NUMBER(12),
    SLOT_POSITION       VARCHAR2(64),
    OPERATIONAL_STATE   VARCHAR2(32) DEFAULT 'IN_SERVICE', -- 'IN_SERVICE', 'RESERVED', 'MAINTENANCE', 'FAULT'
    IP_ADDRESS          VARCHAR2(45),
    POWER_CONSUMPTION_W NUMBER(8,2),
    CREATED_DATE        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_DATE        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ARM_ENTITY_CONTAINER FOREIGN KEY (CONTAINER_ID) REFERENCES ARM_CONTAINERS(CONTAINER_ID)
);

CREATE INDEX IDX_ARM_ENT_TYPE ON ARM_ENTITIES(ENTITY_TYPE);
CREATE INDEX IDX_ARM_ENT_CONT ON ARM_ENTITIES(CONTAINER_ID);
CREATE INDEX IDX_ARM_ENT_STATE ON ARM_ENTITIES(OPERATIONAL_STATE);

COMMENT ON TABLE ARM_ENTITIES IS 'Catalog of physical and virtual entities/devices installed within ARM containers.';


-- 3. CAPACITY ALLOCATIONS & UTILIZATION TABLE
CREATE TABLE ARM_CAPACITY_ALLOCATIONS (
    ALLOCATION_ID       NUMBER(14) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTAINER_ID        NUMBER(12) NOT NULL,
    RESOURCE_METRIC     VARCHAR2(64) NOT NULL,       -- e.g., 'RACK_UNITS', 'POWER_KW', 'BANDWIDTH_GBPS', 'PORT_COUNT'
    TOTAL_PROVISIONED   NUMBER(12,2) NOT NULL,
    CURRENT_USAGE       NUMBER(12,2) NOT NULL,
    RESERVED_CAPACITY   NUMBER(12,2) DEFAULT 0,
    AVAILABLE_CAPACITY  GENERATED ALWAYS AS (TOTAL_PROVISIONED - CURRENT_USAGE - RESERVED_CAPACITY) VIRTUAL,
    UTILIZATION_PCT     GENERATED ALWAYS AS (ROUND((CURRENT_USAGE / NULLIF(TOTAL_PROVISIONED, 0)) * 100, 2)) VIRTUAL,
    MEASUREMENT_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ARM_CAP_CONT FOREIGN KEY (CONTAINER_ID) REFERENCES ARM_CONTAINERS(CONTAINER_ID)
);

CREATE INDEX IDX_ARM_CAP_CONT_METRIC ON ARM_CAPACITY_ALLOCATIONS(CONTAINER_ID, RESOURCE_METRIC);

COMMENT ON TABLE ARM_CAPACITY_ALLOCATIONS IS 'Real-time and historic tracking of capacity metrics across ARM containers and sites.';


-- 4. RELATIONSHIPS & TOPOLOGY TABLE
CREATE TABLE ARM_RELATIONSHIPS (
    RELATION_ID         NUMBER(14) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOURCE_ENTITY_ID    NUMBER(12) NOT NULL,
    SOURCE_ENTITY_NAME  VARCHAR2(255),
    RELATION_TYPE       VARCHAR2(64) NOT NULL,       -- e.g., 'CONTAINS', 'CONNECTED_TO', 'MOUNTS_ON', 'FEEDS_POWER'
    TARGET_ENTITY_ID    NUMBER(12) NOT NULL,
    TARGET_ENTITY_NAME  VARCHAR2(255),
    TARGET_TYPE         VARCHAR2(64),
    IS_ACTIVE           CHAR(1) DEFAULT 'Y' CHECK (IS_ACTIVE IN ('Y', 'N')),
    CREATED_DATE        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_ARM_REL_SOURCE ON ARM_RELATIONSHIPS(SOURCE_ENTITY_ID);
CREATE INDEX IDX_ARM_REL_TARGET ON ARM_RELATIONSHIPS(TARGET_ENTITY_ID);


-- ========================================================================
-- ORACLE STORED PROCEDURES & PACKAGES
-- ========================================================================

-- Package specification for ARM Capacity and Maintenance operations
CREATE OR REPLACE PACKAGE ARM_OPERATIONS_PKG AS
    -- Procedure to calculate utilization and report available capacity for a container
    PROCEDURE GET_CONTAINER_CAPACITY_REPORT (
        p_container_code   IN  VARCHAR2,
        p_out_record       OUT SYS_REFCURSOR
    );

    -- Procedure to reserve capacity for planned container deployment
    PROCEDURE RESERVE_CONTAINER_CAPACITY (
        p_container_code   IN  VARCHAR2,
        p_metric           IN  VARCHAR2,
        p_reserve_amount   IN  NUMBER,
        p_status_message   OUT VARCHAR2
    );
END ARM_OPERATIONS_PKG;
/

CREATE OR REPLACE PACKAGE BODY ARM_OPERATIONS_PKG AS

    PROCEDURE GET_CONTAINER_CAPACITY_REPORT (
        p_container_code   IN  VARCHAR2,
        p_out_record       OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN p_out_record FOR
            SELECT 
                c.CONTAINER_CODE,
                c.CONTAINER_NAME,
                c.CONTAINER_TYPE,
                c.SITE_CODE,
                ca.RESOURCE_METRIC,
                ca.TOTAL_PROVISIONED,
                ca.CURRENT_USAGE,
                ca.AVAILABLE_CAPACITY,
                ca.UTILIZATION_PCT
            FROM ARM_CONTAINERS c
            LEFT JOIN ARM_CAPACITY_ALLOCATIONS ca ON c.CONTAINER_ID = ca.CONTAINER_ID
            WHERE c.CONTAINER_CODE = p_container_code;
    END GET_CONTAINER_CAPACITY_REPORT;

    PROCEDURE RESERVE_CONTAINER_CAPACITY (
        p_container_code   IN  VARCHAR2,
        p_metric           IN  VARCHAR2,
        p_reserve_amount   IN  NUMBER,
        p_status_message   OUT VARCHAR2
    ) IS
        v_container_id NUMBER;
        v_available    NUMBER;
    BEGIN
        SELECT CONTAINER_ID INTO v_container_id 
        FROM ARM_CONTAINERS 
        WHERE CONTAINER_CODE = p_container_code;

        SELECT AVAILABLE_CAPACITY INTO v_available 
        FROM ARM_CAPACITY_ALLOCATIONS 
        WHERE CONTAINER_ID = v_container_id AND RESOURCE_METRIC = p_metric;

        IF v_available >= p_reserve_amount THEN
            UPDATE ARM_CAPACITY_ALLOCATIONS 
            SET RESERVED_CAPACITY = RESERVED_CAPACITY + p_reserve_amount 
            WHERE CONTAINER_ID = v_container_id AND RESOURCE_METRIC = p_metric;
            
            p_status_message := 'SUCCESS: Reserved ' || p_reserve_amount || ' units for ' || p_container_code;
            COMMIT;
        ELSE
            p_status_message := 'FAILED: Insufficient capacity available (' || v_available || ' remaining).';
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            p_status_message := 'ERROR: Container or metric not found.';
        WHEN OTHERS THEN
            p_status_message := 'ERROR: ' || SQLERRM;
            ROLLBACK;
    END RESERVE_CONTAINER_CAPACITY;

END ARM_OPERATIONS_PKG;
